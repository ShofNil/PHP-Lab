<?php
// Sample PHP Code

// Variables
$name = "Alice";
$age = 25;

// Function
function greet($name) {
    return "Hello, " . $name . "!";
}

// Display output
echo greet($name) . "<br>";
echo "Age: " . $age . "<br><br>";

// Loop
echo "Numbers from 1 to 5:<br>";
for ($i = 1; $i <= 5; $i++) {
    echo $i . "<br>";
}
?>